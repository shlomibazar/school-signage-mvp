'use client'
// src/app/admin/screens/new/NewScreenForm.tsx

import { useState, FormEvent } from 'react'
import { useRouter } from 'next/navigation'
import toast from 'react-hot-toast'

// Matching screen outlines in true proportions (16:9 / 9:16) inside the same 64×64 box,
// so both have equal visual weight. Colors follow the card text (blue when selected).
function ScreenShapeIcon({ portrait }: { portrait: boolean }) {
  const [w, h] = portrait ? [32, 56.9] : [56.9, 32]
  const x = (64 - w) / 2, y = (64 - h) / 2
  return (
    <svg width="64" height="64" viewBox="0 0 64 64" aria-hidden="true" className="shrink-0">
      <rect x={x} y={y} width={w} height={h} rx="4" fill="currentColor" fillOpacity="0.12" stroke="currentColor" strokeWidth="2.5" />
      <rect x={x + 4} y={y + 4} width={w - 8} height={h - 8} rx="1.5" fill="currentColor" fillOpacity="0.18" />
    </svg>
  )
}

export default function NewScreenForm() {
  const router = useRouter()
  const [loading, setLoading] = useState(false)
  const [name, setName] = useState('')
  const [orientation, setOrientation] = useState<'LANDSCAPE' | 'PORTRAIT'>('LANDSCAPE')

  async function handleSubmit(e: FormEvent) {
    e.preventDefault()
    if (loading) return
    setLoading(true)
    let created = false
    try {
      const res = await fetch('/api/screens', {
        method:  'POST',
        headers: { 'Content-Type': 'application/json' },
        // The public URL (slug) is generated by the server.
        body:    JSON.stringify({ name: name.trim(), orientation }),
      })
      const data = await res.json()
      if (!res.ok) {
        // Validation errors arrive as an issues array, not a message.
        toast.error(typeof data.error === 'string' ? data.error : 'שגיאה ביצירת המסך')
        return
      }
      toast.success('המסך נוצר בהצלחה!')
      created = true
      router.push(`/admin/editor?screen=${data.data.id}`)
    } catch {
      toast.error('שגיאת רשת')
    } finally {
      // After success keep the button disabled while navigating, so it cannot create a second screen.
      if (!created) setLoading(false)
    }
  }

  return (
    <form onSubmit={handleSubmit} className="bg-white border border-gray-100 rounded-2xl p-6 space-y-5">
      <div>
        <label className="block text-sm font-medium text-gray-700 mb-1.5">שם המסך</label>
        <input
          required
          minLength={2}
          maxLength={100}
          value={name}
          onChange={e => setName(e.target.value)}
          placeholder="לדוגמה: לובי ראשי"
          className="w-full px-3 py-2.5 border border-gray-200 rounded-xl text-sm focus:outline-none focus:ring-2 focus:ring-blue-500/20 focus:border-blue-500"
        />
      </div>

      <div>
        <label className="block text-sm font-medium text-gray-700 mb-2">כיוון מסך</label>
        <div className="grid grid-cols-2 gap-3">
          {[
            { value: 'LANDSCAPE' as const, label: 'אופקי', sub: '16:9' },
            { value: 'PORTRAIT'  as const, label: 'אנכי',  sub: '9:16' },
          ].map(opt => (
            <button
              key={opt.value}
              type="button"
              onClick={() => setOrientation(opt.value)}
              className={`flex flex-col items-center gap-1 py-4 border rounded-xl transition-colors ${
                orientation === opt.value
                  ? 'border-blue-500 bg-blue-50 text-blue-700'
                  : 'border-gray-200 text-gray-600 hover:border-gray-300'
              }`}
            >
              <ScreenShapeIcon portrait={opt.value === 'PORTRAIT'} />
              <span className="text-sm font-medium">{opt.label}</span>
              <span className="text-xs opacity-60">{opt.sub}</span>
            </button>
          ))}
        </div>
      </div>

      <button
        type="submit"
        disabled={loading || name.trim().length < 2}
        className="w-full py-2.5 bg-blue-600 text-white rounded-xl font-medium text-sm hover:bg-blue-700 transition-colors disabled:opacity-50 disabled:cursor-not-allowed"
      >
        {loading ? 'יוצר...' : 'צור מסך ועבור לעורך'}
      </button>
    </form>
  )
}
